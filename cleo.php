                    var bold = /^\*\*/.test(part);
                    var clean = bold ? part.slice(2, -2) : part;
                    clean.split(/\s+/).filter(Boolean).forEach(function (w) {
                        result.push({ t: w, b: bold });
                    });
                });
                return result;
            }

            /* Render n words into el.innerHTML with bold support */
            function render(el, words, n) {
                var html = '', inB = false;
                for (var i = 0; i < n && i < words.length; i++) {
                    var w = words[i], sp = i > 0 ? ' ' : '';
                    if (w.b && !inB) { html += sp + '<b>' + w.t; inB = true; }
                    else if (w.b) { html += ' ' + w.t; }
                    else if (inB) { html += '</b>' + sp + w.t; inB = false; }
                    else { html += sp + w.t; }
                }
                if (inB) html += '</b>';
                el.innerHTML = html;
            }

            /* Type words one by one into el */
            function typeWords(el, words, ms) {
                return new Promise(function (resolve) {
                    var i = 0;
                    function next() {
                        render(el, words, i);
                        if (i >= words.length) { resolve(); return; }
                        i++;
                        setTimeout(next, ms + (Math.random() * 18 - 9));
                    }
                    next();
                });
            }

